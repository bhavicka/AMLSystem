CREATE TABLE tenant_rules (
                              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              rule_id INTEGER NOT NULL UNIQUE,
                              rule_code VARCHAR(255) NOT NULL UNIQUE,
                              rule_name VARCHAR(255) NOT NULL UNIQUE,
                              description TEXT NOT NULL,
                              severity_rate INTEGER NOT NULL,
                              is_active BOOLEAN NOT NULL,
                              is_deleted BOOLEAN DEFAULT FALSE,
                              CONSTRAINT fk_rule_template
                                  FOREIGN KEY (rule_id)
                                      REFERENCES public.rule_templates(id)
);

CREATE TYPE user_role AS ENUM ('compliance_officer', 'bank_admin');
CREATE TYPE user_status AS ENUM ('active', 'inactive');
CREATE TABLE users (
                       id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email VARCHAR(255) UNIQUE NOT NULL,
                       full_name VARCHAR(255) NOT NULL,
                       employee_code VARCHAR(100) UNIQUE NOT NULL,

    -- Using the custom enum types
                       role user_role NOT NULL,
                       status user_status NOT NULL,

                       failed_login_attempts INTEGER DEFAULT 0 NOT NULL,
                       last_login_at TIMESTAMP,

    -- Audit fields
                       created_by INTEGER REFERENCES public.system_users(id),
                       created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                       deactivated_at TIMESTAMP,
                       is_active BOOLEAN DEFAULT TRUE,
                       is_deleted BOOLEAN DEFAULT FALSE
);

CREATE TABLE rule_parameters (
                                 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 rule_id INTEGER NOT NULL,
                                 param_key VARCHAR(255) NOT NULL,
                                 param_value VARCHAR(255) NOT NULL,
                                 min_value VARCHAR(255),
                                 max_value VARCHAR(255),
                                 is_deleted BOOLEAN DEFAULT FALSE,

                                 CONSTRAINT fk_rule
                                     FOREIGN KEY (rule_id)
                                         REFERENCES tenant_rules(id)
                                         ON DELETE CASCADE
);

CREATE TABLE rule_version_parameters (
                                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         rule_param_id INTEGER REFERENCES rule_parameters(id),
                                         param_key VARCHAR(255) NOT NULL,
                                         old_param_value VARCHAR(255) NOT NULL,
                                         new_param_value VARCHAR(255) NOT NULL,
                                         changed_by INTEGER REFERENCES users(id),
                                         changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                         is_deleted BOOLEAN DEFAULT FALSE
);
CREATE TYPE batch_status AS ENUM ('uploaded', 'processing', 'completed');
CREATE TABLE transaction_batches (
                                     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     uploaded_by INTEGER NOT NULL,
                                     file_name VARCHAR(255) NOT NULL,
                                     file_storage_path VARCHAR(500) NOT NULL,
                                     total_records INTEGER NOT NULL,
                                     status batch_status NOT NULL DEFAULT 'uploaded',
                                     uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                                     processed_at TIMESTAMP,
                                     is_deleted BOOLEAN DEFAULT FALSE,

                                     CONSTRAINT fk_uploaded_by
                                         FOREIGN KEY (uploaded_by)
                                             REFERENCES users(id)
);
CREATE TABLE batch_validation_errors (
                                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         batch_id INTEGER NOT NULL,
                                         row_number INTEGER NOT NULL,
                                         field_name VARCHAR(255),
                                         error_message VARCHAR(500) NOT NULL,

                                         CONSTRAINT fk_batch_validation_error
                                             FOREIGN KEY (batch_id)
                                                 REFERENCES transaction_batches(id)
                                                 ON DELETE CASCADE
);

CREATE TYPE transaction_type AS ENUM ('debit', 'credit');
CREATE TYPE transaction_mode AS ENUM ('cash', 'net_banking', 'upi', 'cheque');

CREATE TABLE transactions (
                              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              batch_id INTEGER NOT NULL,
                              account_number VARCHAR(255) NOT NULL,
                              transaction_date DATE,
                              transaction_type transaction_type,
                              transaction_mode transaction_mode,
                              amount DECIMAL(19, 2) NOT NULL,
                              transaction_reference_number VARCHAR(255) NOT NULL,
                              created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                              is_deleted BOOLEAN DEFAULT FALSE,

                              CONSTRAINT fk_batch_transaction
                                  FOREIGN KEY (batch_id)
                                      REFERENCES transaction_batches(id)
                                      ON DELETE CASCADE
);

CREATE TYPE occupation_type_enum AS ENUM (
