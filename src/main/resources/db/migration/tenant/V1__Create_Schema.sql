CREATE TABLE customers (
                           id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           client_id VARCHAR(255) UNIQUE NOT NULL,
                           first_name VARCHAR(255) NOT NULL,
                           last_name VARCHAR(255) NOT NULL,
                           middle_name VARCHAR(255),
                           aadhaar_number VARCHAR(12) NOT NULL UNIQUE,
                           pan VARCHAR(10) NOT NULL UNIQUE,
                           occupation VARCHAR(255) NOT NULL,
                           occupation_type occupation_type_enum NOT NULL,
                           is_pep BOOLEAN DEFAULT FALSE,
                           risk_rate INTEGER CHECK (risk_rate >= 1 AND risk_rate <= 10),
                           monthly_income DECIMAL(19, 2) NOT NULL,
                           dob DATE NOT NULL,
                           profession_multiplier DECIMAL(5, 2),
                           family_code VARCHAR(255),
                           is_deleted BOOLEAN DEFAULT FALSE
);

CREATE TYPE account_type AS ENUM ('current', 'saving', 'salary', 'fd');
CREATE TYPE account_status AS ENUM ('active', 'inactive', 'frozen', 'dormant', 'closed');

CREATE TABLE accounts (
                          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          client_id VARCHAR(255) NOT NULL,
                          account_number VARCHAR(255) NOT NULL UNIQUE,
                          account_type account_type NOT NULL,
                          account_status account_status NOT NULL DEFAULT 'active',
                          is_deleted BOOLEAN DEFAULT FALSE,

                          CONSTRAINT fk_account_customer
                              FOREIGN KEY (client_id)
                                  REFERENCES customers(client_id)
);

CREATE TYPE case_status AS ENUM (
    'open', 'pending_review', 'under_investigation', 'on_hold',
    'escalated', 'closed_as_false_positive', 'reported_to_fiu', 'closed'
);

CREATE TABLE cases (
                       id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       case_reference_number VARCHAR(255) NOT NULL UNIQUE,
                       status case_status NOT NULL DEFAULT 'open',
                       assigned_to INTEGER,
                       assigned_by INTEGER,
                       assigned_at TIMESTAMP,
                       closed_at TIMESTAMP,
                       created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                       notes TEXT,
                       is_deleted BOOLEAN DEFAULT FALSE,

                       CONSTRAINT fk_case_assigned_to FOREIGN KEY (assigned_to) REFERENCES users(id),
                       CONSTRAINT fk_case_assigned_by FOREIGN KEY (assigned_by) REFERENCES users(id)
);

CREATE TYPE alert_status AS ENUM ('new', 'dismissed', 'converted_to_case');

CREATE TABLE alerts (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        transaction_id INTEGER NOT NULL,
                        rule_id INTEGER NOT NULL,
                        case_id INTEGER,
                        status alert_status NOT NULL DEFAULT 'new',
                        generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        is_deleted BOOLEAN DEFAULT FALSE,

                        CONSTRAINT fk_alert_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id),
                        CONSTRAINT fk_alert_rule FOREIGN KEY (rule_id) REFERENCES tenant_rules(id),
                        CONSTRAINT fk_alert_case FOREIGN KEY (case_id) REFERENCES cases(id)
);

CREATE TABLE str_filings (
                             id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             case_id INTEGER NOT NULL,
                             filed_by INTEGER NOT NULL,
                             supporting_notes TEXT,
                             reference_number VARCHAR(255) NOT NULL UNIQUE,
                             submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                             pdf_storage_path VARCHAR(500) NOT NULL,
                             is_deleted BOOLEAN DEFAULT FALSE,

                             CONSTRAINT fk_str_case FOREIGN KEY (case_id) REFERENCES cases(id),
                             CONSTRAINT fk_str_user FOREIGN KEY (filed_by) REFERENCES users(id)
);

CREATE TYPE event_type AS ENUM (
    'alert_generated', 'case_assigned', 'case_escalated', 'str_filed', 'batch_failed'
);

CREATE TABLE notifications (
                               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               user_id INTEGER NOT NULL,
                               event_type event_type NOT NULL,
                               related_record_id INTEGER,
                               related_record_table_name VARCHAR(100),
                               message TEXT NOT NULL,
                               created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                               is_deleted BOOLEAN DEFAULT FALSE,

                               CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id)
);